const DICTS: Record<"en" | "ja" | "zh-TW", Dict> = { en, ja, "zh-TW": zhTW };

export const UI_LANGS: { code: "en" | "ja" | "zh-TW"; label: string }[] = [
  { code: "en", label: "English" },
  { code: "ja", label: "日本語" },
  { code: "zh-TW", label: "繁體中文" },
];

export function t(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const dict = lang === "ja" || lang === "zh-TW" ? DICTS[lang] : DICTS.en;
  let s: string = dict[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

