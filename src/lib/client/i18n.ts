export function countryName(code: string, lang: Lang): string {
  const fixed = COUNTRY_NAMES[code];
  if (fixed) return lang === "ja" ? fixed[1] : lang === "zh-TW" ? fixed[2] : fixed[0];
  try {
    return new Intl.DisplayNames([lang], { type: "region" }).of(code) ?? code;
  } catch {
    return code;
  }
}

export function localized(text: { en: string } & Partial<Record<Lang, string>>, lang: Lang): string {
  return text[lang] ?? text.en;
}

export function formatDistance(m: number): string {
  if (Math.round(m / 10) * 10 < 1000) return `${Math.round(m / 10) * 10} m`;
  return `${(m / 1000).toFixed(1)} km`;
}
